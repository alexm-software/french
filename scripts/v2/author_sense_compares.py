def fold(s):
    s = s.replace("œ", "oe").replace("æ", "ae").replace("Œ", "Oe")
    s = unicodedata.normalize("NFD", s)
    return "".join(c for c in s if unicodedata.category(c) != "Mn")


def sources_for(lemma_a, lemma_b):
    out = []
    for lem in (lemma_a, lemma_b):
        if " " not in lem and "'" not in lem and "’" not in lem:
            out.append("https://www.cnrtl.fr/definition/" + fold(lem))
        out.append("https://www.larousse.fr/dictionnaires/francais/" + urllib.parse.quote(lem))
    return out


