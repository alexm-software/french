def prior_support():
    """Keep excerpts already stored for pairs this pass is not rewriting."""
    path = ROOT / "data" / "source" / "sense_compares.json"
    if not path.exists():
        return {}
    doc = json.loads(path.read_text(encoding="utf-8"))
    out = {}
    for e in doc.get("edges") or []:
        if e.get("support"):
            out[tuple(sorted((e["a"], e["b"])))] = e["support"]
    return out


def settle(support):
    """A line that is not on the recorded page is uncertain, not a quote."""
    if not support:
        return support
    import importlib.util
    spec = importlib.util.spec_from_file_location("quote_check", ROOT / "scripts" / "qa" / "quote_check.py")
    qc = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(qc)
    corpus = qc.load_corpus()
    if not corpus:
        return support
    out = []
    for s in support:
        item = dict(s)
        if item.get("kind") in ("uncertain", "paraphrase"):
            item["kind"] = "uncertain"
            out.append(item)
            continue
        text = corpus.get(item.get("url") or "")
        if text and qc.excerpt_in(item.get("excerpt") or "", text):
            item.pop("kind", None)
            out.append(item)
        else:
            item["kind"] = "uncertain"
            out.append(item)
    return out


def build_edges(vocab, defs=None):
    prev = prior_support()
    edges, deferred = [], []
    for row in RAW:
        a, b, axes, a_note, b_note = row[:5]
        a_ex = row[5] if len(row) > 5 else None
        b_ex = row[6] if len(row) > 6 else None
        key = tuple(sorted((a, b)))
        # Hand-read excerpts win. Otherwise keep a pair already published with its excerpt.
        # Do not fill a gap from the first sentence of a scraped page.
        support = settle(HAND.get(key) or SUPPORT.get(key) or prev.get(key))
        if not support:
            deferred.append({"a": a, "b": b, "reason": "no hand-checked sense excerpt"})
            continue
        edge = {
            "a": a, "b": b, "axes": axes,
            "a_note": a_note, "b_note": b_note,
            "sources": [s["url"] for s in support],
            "support": support,
            # A quote is a passage on the recorded page. Uncertain support is not a verification.
            "verified": all((s.get("kind") or "quote") == "quote" for s in support),
        }
        if a_ex:
            edge["a_ex"] = a_ex
        if b_ex:
            edge["b_ex"] = b_ex
        edges.append(edge)
    return edges, deferred


def main():
    vocab = load_vocab()
    edges, deferred = build_edges(vocab)
    problems = validate(vocab, edges)
    if problems:
        print("\n".join(problems[:40]))
        raise SystemExit(f"{len(problems)} problem(s)")
    doc = {
        "about": "Learner cards use a_note, b_note, and labeled examples only. verified true means every support item is a quote of the relevant sense from a page that was opened. kind uncertain means the excerpt was not confirmed on the recorded page and is not a verification. A substring match is not treated as proof of the sense. au/aux and foot/football have no edge. Neuf the number and neuf brand-new are separate entries. Le poêle is the heater and la poêle is the frying pan.",
        "edges": edges,
    }
    path = ROOT / "data" / "source" / "sense_compares.json"
    path.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    (ROOT / "data" / "source" / "sense_compare_deferred.json").write_text(
        json.dumps({"deferred_unsupported": deferred}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    quoted = sum(1 for e in edges if e["verified"])
    print(f"wrote {len(edges)} edges; {quoted} fully quoted; {len(edges)-quoted} with uncertain evidence; deferred {len(deferred)}")


if __name__ == "__main__":
    main()
